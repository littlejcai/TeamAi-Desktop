const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
const marker = "# Auto-generated by teamai — do not edit.";
const shQuote = (value) => "'" + value.replaceAll("'", "'\"'\"'") + "'";
// Only repair the disposable wrapper core just generated for this distribution.
// Its stock node argv[0] fallback otherwise points at Electron without RUN_AS_NODE.
async function repairWrapper({
  wrapper,
  entry,
  executable,
  platform = process.platform,
}) {
  const existing = await fs.readFile(wrapper, "utf8").catch(() => null);
  if (!existing || !existing.includes(marker) || !existing.includes(entry))
    return false;
  const shellPath = (p) => (platform === "win32" ? p.replaceAll("\\", "/") : p);
  const content = `#!/bin/sh\n${marker}\n# Desktop-owned runtime bridge; regenerated on init/pull.\nELECTRON_RUN_AS_NODE=1 exec ${shQuote(shellPath(executable))} ${shQuote(shellPath(entry))} "$@"\n`;
  await fs.writeFile(wrapper, content, { mode: 0o755 });
  if (platform === "win32") {
    const escaped = (p) => p.replaceAll("%", "%%");
    await fs.writeFile(
      wrapper + ".cmd",
      `@echo off\r\nset "ELECTRON_RUN_AS_NODE=1"\r\n"${escaped(executable)}" "${escaped(entry)}" %*\r\n`,
    );
  }
  return true;
}
async function repairGeneratedWrapper() {
  const home =
    process.env.HOME?.trim() || process.env.USERPROFILE?.trim() || os.homedir();
  return repairWrapper({
    wrapper: path.join(home, ".teamai", "bin", "teamai"),
    entry: require.resolve("teamai-cli/dist/index.js"),
    executable: process.execPath,
  });
}
module.exports = { repairWrapper, repairGeneratedWrapper, marker };
